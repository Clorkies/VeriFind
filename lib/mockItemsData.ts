function pic(seed: string, w = 480, h = 320) {
  return `https://picsum.photos/seed/${seed}/${w}/${h}`;
}

/** Deterministic 64-char hex (mock chain id) per row index. */
function txForSlot(slot: number): string {
  let out = "";
  for (let k = 0; k < 64; k++) {
    out += ((slot * 17 + k * 13) % 16).toString(16);
  }
  return out;
}

